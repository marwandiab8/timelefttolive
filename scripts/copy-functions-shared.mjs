// Copies the pure utilities the Cloud Functions share with the app (the weekly digest and everything it imports) from
// src/utils into functions/shared, which is generated and not committed. Runs before deploying functions, before the
// functions tests and before the emulators start, so the copy can't drift from the app.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src', 'utils');
const target = join(root, 'functions', 'shared');
const ENTRY_POINTS = ['weeklyDigest.js'];

const seen = new Set();
const queue = [...ENTRY_POINTS];
while (queue.length) {
  const file = queue.shift();
  if (seen.has(file)) continue;
  seen.add(file);
  const text = readFileSync(join(source, file), 'utf8');
  for (const match of text.matchAll(/from\s+'([^']+)'/g)) {
    const specifier = match[1];
    if (!specifier.startsWith('./') || specifier.includes('/', 2)) {
      throw new Error(`${file} imports ${specifier}; functions/shared can only hold files from src/utils that import each other.`);
    }
    queue.push(specifier.slice(2));
  }
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
writeFileSync(join(target, 'package.json'), `${JSON.stringify({ type: 'module', private: true }, null, 2)}\n`);
writeFileSync(join(target, 'README.md'), 'Generated by scripts/copy-functions-shared.mjs from src/utils. Do not edit; it is replaced on every run.\n');
for (const file of [...seen].sort()) writeFileSync(join(target, file), readFileSync(join(source, file)));
console.log(`functions/shared: ${[...seen].sort().join(', ')}`);
